#!/usr/bin/env node
/**
 * Build dist/dsh-kicad: the whole bundle as ONE self-contained package, so it can be
 * installed from Git (`git+https://…#<commit>&path:/dist/dsh-kicad`) or a tarball,
 * where pnpm cannot resolve the monorepo's workspace: siblings.
 *
 *   pnpm run build && node scripts/pack-dist.mjs
 *
 * Every plugin becomes a subpath of the package (dsh-kicad/bridge, /tools, /policy,
 * /skills); the Web UI is the package root, whose row carries the browser half.
 * Only @deepseek-ai/* stay external (dsh supplies them at runtime).
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join, relative, resolve } from 'node:path'
import { build } from 'esbuild'
import { buildClient } from './build-client.mjs'

const root = resolve(import.meta.dirname, '..')
const out = join(root, 'dist/dsh-kicad')
const pkgs = join(root, 'packages')
const bundlePkg = JSON.parse(readFileSync(join(pkgs, 'kicad-bundle/package.json'), 'utf8'))
const NAME = 'dsh-kicad'

const plugins = {
  bridge: 'kicad-bridge',
  tools: 'tool-kicad',
  policy: 'kicad-policy',
  skills: 'kicad-skills',
}

rmSync(out, { recursive: true, force: true })
mkdirSync(join(out, 'lib'), { recursive: true })

for (const [sub, dir] of Object.entries(plugins)) {
  await build({
    entryPoints: [join(pkgs, dir, 'src/index.ts')],
    outfile: join(out, 'lib', `${sub}.js`),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    packages: 'bundle',
    external: ['@deepseek-ai/*'],
    legalComments: 'none',
    logLevel: 'warning',
  })
  mkdirSync(join(out, 'locale', sub), { recursive: true })
  for (const lang of ['en', 'zh']) cpSync(join(pkgs, dir, `locale/${lang}.json`), join(out, 'locale', sub, `${lang}.json`))
}
// Web UI: the root row (host marker + browser half).
await build({
  entryPoints: [join(pkgs, 'client-ui-kicad/src/index.ts')],
  outfile: join(out, 'lib/index.js'), bundle: true, platform: 'node', format: 'esm', logLevel: 'warning',
})
await buildClient({ cwd: join(pkgs, 'client-ui-kicad'), out: join(out, 'lib/client.js'), id: NAME })

// Runtime resources the plugins resolve relative to lib/.
cpSync(join(pkgs, 'kicad-bridge/sidecar/src'), join(out, 'sidecar/src'), { recursive: true, filter: p => !p.includes('__pycache__') })
for (const f of ['pyproject.toml', 'README.md', 'uv.lock']) cpSync(join(pkgs, 'kicad-bridge/sidecar', f), join(out, 'sidecar', f))
cpSync(join(pkgs, 'kicad-skills/skills'), join(out, 'skills'), { recursive: true })
cpSync(join(pkgs, 'client-ui-kicad/vendor/kicanvas'), join(out, 'third_party/kicanvas'), { recursive: true, filter: p => !p.endsWith('.js') && !p.endsWith('.d.ts') })
cpSync(join(pkgs, 'kicad-bundle/icon.svg'), join(out, 'icon.svg'))
cpSync(join(pkgs, 'kicad-bundle/presets'), join(out, 'presets'), { recursive: true })
cpSync(join(root, 'LICENSE'), join(out, 'LICENSE'))
mkdirSync(join(out, 'locale'), { recursive: true })
for (const lang of ['en', 'zh']) cpSync(join(pkgs, 'kicad-bundle', `locale/${lang}.json`), join(out, 'locale', `${lang}.json`))

// Same rows as packages/kicad-bundle/cordis.patch.yml, renamed to subpaths.
let patch = readFileSync(join(pkgs, 'kicad-bundle/cordis.patch.yml'), 'utf8')
for (const [sub, dir] of Object.entries(plugins)) {
  const from = JSON.parse(readFileSync(join(pkgs, dir, 'package.json'), 'utf8')).name
  patch = patch.replaceAll(`'${from}'`, `'${NAME}/${sub}'`)
}
patch = patch.replaceAll(`'dsh-client-ui-kicad'`, `'${NAME}'`)
if (/'dsh-(kicad|tool|client)-[a-z-]+'/.test(patch)) throw new Error('unmapped row in cordis.patch.yml')
writeFileSync(join(out, 'cordis.patch.yml'), `# Generated by scripts/pack-dist.mjs from packages/kicad-bundle/cordis.patch.yml\n${patch}`)

const exports = {
  '.': './lib/index.js',
  './client': './lib/client.js',
  './package.json': './package.json',
  './cordis.patch.yml': './cordis.patch.yml',
  './presets/*.yml': './presets/*.yml',
  './locale/*.json': './locale/*.json',
  './icon': './icon.svg',
}
for (const sub of Object.keys(plugins)) {
  exports[`./${sub}`] = `./lib/${sub}.js`
  exports[`./${sub}/locale/*.json`] = `./locale/${sub}/*.json`
  exports[`./${sub}/icon`] = './icon.svg'
}
const clientPkg = JSON.parse(readFileSync(join(pkgs, 'client-ui-kicad/package.json'), 'utf8'))
const manifest = {
  name: NAME,
  version: bundlePkg.version,
  description: bundlePkg.description,
  license: 'MIT',
  type: 'module',
  icon: './icon.svg',
  main: './lib/index.js',
  exports,
  files: ['lib', 'sidecar', 'skills', 'presets', 'locale', 'third_party', 'icon.svg', 'cordis.patch.yml', 'LICENSE', 'README.md'],
  keywords: ['dsh', 'dsh-bundle', 'kicad', 'eda', 'schematic', 'pcb', 'erc'],
  engines: bundlePkg.engines,
  peerDependencies: {
    '@deepseek-ai/cordis': '^4.0.5',
    '@deepseek-ai/schemastery': '^3.18.5',
    '@deepseek-ai/dsh-tools': '^0.2.1-rc.2',
    '@deepseek-ai/dsh-llm': '^0.2.1-rc.2',
  },
  dsh: {
    bundle: { patch: ['./cordis.patch.yml', './presets/eda.patch.yml'] },
    client: clientPkg.dsh.client,
  },
  repository: { type: 'git', url: 'git+https://github.com/LuYanFCP/dsh-kicad.git', directory: 'dist/dsh-kicad' },
  homepage: 'https://github.com/LuYanFCP/dsh-kicad#readme',
}
writeFileSync(join(out, 'package.json'), JSON.stringify(manifest, null, 2) + '\n')

// The repository root is a bundle too, so pasting the plain GitHub URL into dsh's
// "Add plugin" (which installs the repo root) works. Same package name and rows; every
// path points into dist/dsh-kicad. Development fields (scripts, devDependencies) stay.
const rootPath = join(root, 'package.json')
const rootPkg = JSON.parse(readFileSync(rootPath, 'utf8'))
const inDist = p => p.replace(/^\.\//, './dist/dsh-kicad/')
const rootManifest = {
  name: NAME,
  version: manifest.version,
  description: manifest.description,
  license: manifest.license,
  private: true,
  type: 'module',
  packageManager: rootPkg.packageManager,
  icon: inDist(manifest.icon),
  main: inDist(manifest.main),
  exports: Object.fromEntries(Object.entries(manifest.exports).map(([k, v]) => [k, k === './package.json' ? v : inDist(v)])),
  engines: { ...rootPkg.engines, ...manifest.engines },
  peerDependencies: manifest.peerDependencies,
  dsh: {
    bundle: { patch: manifest.dsh.bundle.patch.map(inDist) },
    client: manifest.dsh.client,
  },
  keywords: manifest.keywords,
  repository: { type: 'git', url: manifest.repository.url },
  homepage: manifest.homepage,
  scripts: rootPkg.scripts,
  devDependencies: rootPkg.devDependencies,
}
writeFileSync(rootPath, JSON.stringify(rootManifest, null, 2) + '\n')
writeFileSync(join(out, 'README.md'), `# dsh-kicad (distribution)

Generated by \`scripts/pack-dist.mjs\` from the dsh-kicad monorepo — do not edit by hand.
One self-contained package with every plugin of the KiCad bundle, installable without npm:

    dsh plugin --profile web add "git+https://github.com/LuYanFCP/dsh-kicad.git#<commit>&path:/dist/dsh-kicad"

See the [project README](../../README.md). Third-party notices: \`third_party/kicanvas/\`.
`)
// Git installs only see committed files: refuse a distribution that .gitignore would drop.
const files = execFileSync('find', [out, '-type', 'f'], { encoding: 'utf8' }).trim().split('\n')
let ignored = ''
try {
  ignored = execFileSync('git', ['-C', root, 'check-ignore', '--stdin'], { input: files.map(f => relative(root, f)).join('\n'), encoding: 'utf8' }).trim()
} catch (error) {
  if (error.status !== 1) throw error // 1 = nothing ignored
}
if (ignored) throw new Error(`these distribution files are git-ignored and would be missing from a Git install:\n${ignored}`)
console.log(`packed ${NAME}@${manifest.version} → ${out} (${files.length} files, none git-ignored)`)
